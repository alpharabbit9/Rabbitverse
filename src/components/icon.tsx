export function Icon({
  name,
  className,
  size = 18,
  strokeWidth = 2,
  style,
}: {
  name: string;
  className?: string;
  size?: number;
  strokeWidth?: number;
  style?: React.CSSProperties;
}) {
  const Cmp = REGISTRY[name] ?? Sparkles;
  return <Cmp className={className} size={size} strokeWidth={strokeWidth} style={style} />;
}
